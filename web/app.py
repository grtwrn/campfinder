MAX_UPLOAD = 2 * 1024 * 1024          # 2 MB is a very large cookbook
LOGIN_WINDOW, LOGIN_MAX = 300, 8      # attempts per IP per 5 minutes

app = Flask(__name__)
app.config.update(
    MAX_CONTENT_LENGTH=MAX_UPLOAD,
    SESSION_COOKIE_HTTPONLY=True,
    SESSION_COOKIE_SAMESITE="Lax",
    SESSION_COOKIE_SECURE=bool(os.environ.get("FLY_APP_NAME")),
)
# On Fly the secret must be set; locally a generated one is fine (it only
# means sessions reset on restart).
app.secret_key = os.environ.get("SECRET_KEY") or os.urandom(32)

_login_hits = {}


# ------------------------------------------------------------ plumbing --
@app.before_request
def load_user():
    g.user = store.session_user(session.get("t"))
    if request.method == "POST" and g.user:
        sent = request.form.get("csrf", "")
        if not sent or sent != g.user["csrf"]:
            abort(400, "bad csrf token")


@app.after_request
def secure_headers(resp):
    resp.headers.setdefault("X-Content-Type-Options", "nosniff")
    resp.headers.setdefault("X-Frame-Options", "DENY")
    resp.headers.setdefault("Referrer-Policy", "same-origin")
    resp.headers.setdefault(
        "Content-Security-Policy",
        "default-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:")
    return resp


@app.context_processor
def inject():
    return {"user": g.get("user"), "csrf": (g.get("user") or {}).get("csrf", "")}


def require_login():
    if not g.get("user"):
        return redirect(url_for("login", next=request.path))
    return None


def rate_limited(key):
    now = time.time()
    hits = [t for t in _login_hits.get(key, []) if now - t < LOGIN_WINDOW]
    _login_hits[key] = hits + [now]
    return len(hits) >= LOGIN_MAX


# ------------------------------------------------------------ accounts --
@app.route("/")
def index():
    if g.get("user"):
        return redirect(url_for("trips"))
    return render_template("landing.html")


@app.route("/signup", methods=["GET", "POST"])
def signup():
    if request.method == "POST":
        email = (request.form.get("email") or "").strip()
        pw = request.form.get("password") or ""
        name = (request.form.get("name") or "").strip()
        if "@" not in email or len(email) > 200:
            flash("Enter a valid email address.")
        elif len(pw) < 10:
            flash("Use a password of at least 10 characters.")
        else:
            try:
                uid = store.create_user(email, pw, name)
            except sqlite3.IntegrityError:
                flash("That email already has an account.")
            except Exception:
                # Never disguise a real failure as a duplicate-email message -
                # that sent me chasing the wrong bug once already.
                app.logger.exception("signup failed")
                flash("Something went wrong creating the account.")
            else:
                session["t"] = store.start_session(uid)
                return redirect(url_for("cookbook"))
    return render_template("signup.html")


@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        if rate_limited(request.remote_addr or "?"):
            flash("Too many attempts. Wait a few minutes and try again.")
            return render_template("login.html"), 429
        user = store.verify_user(request.form.get("email", ""),
                                 request.form.get("password", ""))
        if user:
            session["t"] = store.start_session(user["id"])
            nxt = request.args.get("next", "")
            return redirect(nxt if nxt.startswith("/") else url_for("trips"))
        flash("Email or password is incorrect.")
    return render_template("login.html")


@app.route("/logout", methods=["POST"])
def logout():
    store.end_session(session.pop("t", None))
    return redirect(url_for("index"))


