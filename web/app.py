"""Camp Planner - a small Flask site for cookbooks and trip planners.

Deliberately does NOT do campsite availability search. That part of campfinder
reads booking systems whose terms restrict automated access and permit only
personal, non-commercial use; running it from a shared host for other people
would breach that and would be blocked within days anyway. Everything here is
the user's own data - their recipes, their menus, their trips - which hosts
cleanly. Availability search stays a local CLI.

The planner itself is generated by plan.py, the same module the CLI uses, so
the site and the command line cannot drift apart.
"""

