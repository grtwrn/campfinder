@app.route("/cookbook/import", methods=["POST"])
def cookbook_import():
    if (r := require_login()):
        return r
    text, filename = request.form.get("text", ""), ""
    upload = request.files.get("file")
    if upload and upload.filename:
        filename = upload.filename
        raw = upload.read(MAX_UPLOAD + 1)
        if len(raw) > MAX_UPLOAD:
            flash("That file is larger than 2 MB.")
            return redirect(url_for("cookbook"))
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            flash("Upload a text file — .md, .txt, .json or .csv. "
                  "PDFs and images aren't supported yet.")
            return redirect(url_for("cookbook"))

    parsed = cook.parse(text, filename)
    if not parsed:
        flash("Couldn't find any recipes in that. Each recipe needs a name "
              "line, then its ingredients — one per line.")
    else:
        for name, ings in parsed.items():
            store.save_recipe(g.user["id"], name, ings, filename or "pasted")
        flash(f"Imported {len(parsed)} recipe(s): "
              + ", ".join(list(parsed)[:6])
              + ("…" if len(parsed) > 6 else ""))
    return redirect(url_for("cookbook"))


