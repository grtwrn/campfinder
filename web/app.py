# ------------------------------------------------------------- planner --
def hydrate(user_id, data):
    """Attach only the cookbook recipes this trip's menu actually uses.

    Unreferenced recipes are still shopped for by plan.py (that's how
    "Breakfasts (all days)" works), so handing it the whole cookbook would
    buy groceries for every recipe the user has ever saved.
    """
    book = store.recipe_map(user_id)
    used = set()
    for e in data.get("menu", []):
        for slot in ("breakfast", "lunch", "dinner"):
            meal = (e.get(slot) or "").strip()
            if meal in book:
                used.add(meal)
    for name in data.get("always", []):
        if name in book:
            used.add(name)
    return {**data, "recipes": {n: book[n] for n in sorted(used)}}


@app.route("/trips/<int:tid>/grocery")
def grocery(tid):
    if (r := require_login()):
        return r
