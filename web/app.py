# --------------------------------------------------------------- trips --
def blank_trip(name, start, end):
    return {"trip": {"name": name, "start": start, "end": end},
            "legs": [], "days": [], "menu": [], "extras": [],
            "unplaced": [], "menu_notes": []}


@app.route("/trips", methods=["GET", "POST"])
def trips():
    if (r := require_login()):
        return r
    if request.method == "POST":
        name = (request.form.get("name") or "Untitled trip").strip()
        start = request.form.get("start") or dt.date.today().isoformat()
        end = request.form.get("end") or start
        if end < start:
            flash("The end date is before the start date.")
            return redirect(url_for("trips"))
        tid = store.create_trip(g.user["id"], name,
                                blank_trip(name, start, end))
        return redirect(url_for("trip_edit", tid=tid))
    return render_template("trips.html", trips=store.list_trips(g.user["id"]),
                           today=dt.date.today().isoformat())


@app.route("/trips/<int:tid>", methods=["GET", "POST"])
def trip_edit(tid):
    if (r := require_login()):
        return r
    row = store.get_trip(g.user["id"], tid)
    if not row:
        abort(404)
    data = row["data"]

    if request.method == "POST":
        t = data.setdefault("trip", {})
        t["name"] = (request.form.get("name") or t.get("name", "")).strip()
        t["start"] = request.form.get("start") or t["start"]
        t["end"] = request.form.get("end") or t["end"]
        if t["end"] < t["start"]:
            flash("The end date is before the start date — not saved.")
            return redirect(url_for("trip_edit", tid=tid))

        dogname = (request.form.get("dog") or "").strip()
        data["dog"] = {"name": dogname} if dogname else None
        for flag in ("water", "hiking", "cold"):
            data[flag] = bool(request.form.get(flag))

        days, menu = [], []
        for day in plan.daterange(plan.d(t["start"]), plan.d(t["end"])):
            key = day.isoformat()
            items = [ln.strip() for ln in
                     (request.form.get(f"day_{key}") or "").splitlines()
                     if ln.strip()]
            if items:
                days.append({"date": key, "items": items})
            slots = {s: (request.form.get(f"{s}_{key}") or "").strip()
                     for s in ("breakfast", "lunch", "dinner")}
            if any(slots.values()):
                menu.append({"date": key, **slots})
        data["days"], data["menu"] = days, menu

        data["legs"] = []
        for i in range(int(request.form.get("leg_count") or 0)):
            loc = (request.form.get(f"leg_loc_{i}") or "").strip()
            if not loc:
                continue
            data["legs"].append({
                "name": f"Leg {len(data['legs']) + 1}",
                "start": request.form.get(f"leg_start_{i}") or t["start"],
                "end": request.form.get(f"leg_end_{i}") or t["end"],
                "location": loc,
                "confirmation": (request.form.get(f"leg_conf_{i}") or "").strip()})

        data["extras"] = []
        for line in (request.form.get("extras") or "").splitlines():
            line = line.strip()
            if not line:
                continue
            item, _, why = line.partition("|")
            data["extras"].append({"item": item.strip(), "for": why.strip()})

        data["unplaced"] = [ln.strip() for ln in
                            (request.form.get("unplaced") or "").splitlines()
                            if ln.strip()]
        store.save_trip(g.user["id"], tid, data, t["name"])
        flash("Saved.")
        return redirect(url_for("trip_edit", tid=tid))

    t = data["trip"]
    days = plan.daterange(plan.d(t["start"]), plan.d(t["end"]))
    by_day = {e["date"]: e for e in data.get("days", [])}
    by_menu = {e["date"]: e for e in data.get("menu", [])}
    return render_template(
        "trip.html", trip=row, data=data, days=days, by_day=by_day,
        by_menu=by_menu, label=plan.label,
        recipes=sorted(store.recipe_map(g.user["id"])),
        extras_text="\n".join(
            f"{e['item']} | {e.get('for','')}" if isinstance(e, dict) else str(e)
            for e in data.get("extras", [])))


